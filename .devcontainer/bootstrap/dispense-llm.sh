#!/usr/bin/env bash
# ISI-6996 (WS3 of ISI-6992) — room-password → model-proxy key dispenser client.
#
# Given ONLY the room password (WORKSHOP_ROOM_PASSWORD), fetch this attendee's
# LiteLLM-proxy endpoint + a freshly minted, budget-capped virtual key from the
# room dispenser and write them to .workshop-llm.env (gitignored). That file is
# then sourced by cluster/versions.env (→ install.sh / install-agents.sh) and by
# ~/.bashrc (→ interactive shells running the Phoenix/dt-evals evals), so ALL
# DeepSeek traffic — kagent agents, Phoenix evals, the dt-evals judge — flows
# through the proxy with NO raw provider key present anywhere in the repo or env.
#
# Contract (published by WS2 / ISI-6995, live on the proxy host):
#   GET  https://<funnel-host>/dispense     (Tailscale Funnel, HTTPS 443)
#   hdr  X-Room-Password: <pw>
#   200  { "proxy_url": "https://<funnel-host>", "virtual_key": "sk-...", "model": "deepseek-chat" }
#   401  bad/absent password
#
# Idempotent & re-runnable: re-run after the room password rotates to mint a fresh
# key. Non-fatal by design — the caller (postCreate) warns and continues so the
# rest of the stack still installs if the password is missing or the host is down.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "${SCRIPT_DIR}/lib.sh"

# Dispenser endpoint — REQUIRED, facilitator-supplied (ISI-7000). NOT hardcoded:
# the proxy host is published over a rotatable Tailscale Funnel, so the URL must
# never live in this (public) repo. The host distributes it alongside the room
# password; attendees set it as the WORKSHOP_DISPENSER_URL Codespace secret. The
# room password still gates the endpoint (keys are per-attendee, budget-capped,
# single-model). Fail-closed if absent — mirrors WORKSHOP_ROOM_PASSWORD below.
DISPENSER_URL="${WORKSHOP_DISPENSER_URL:-}"
OUT="${REPO_ROOT}/.workshop-llm.env"

if [ -z "${DISPENSER_URL}" ]; then
  warn "WORKSHOP_DISPENSER_URL is not set — cannot locate the model-proxy dispenser."
  warn "Set it in the 'Create codespace with options…' dialog (the dispenser URL from the workshop host,"
  warn "alongside the room password), then rebuild. Without it the agents + Phoenix/dt-evals evals have no model key (the rest still installs)."
  exit 1
fi

if [ -z "${WORKSHOP_ROOM_PASSWORD:-}" ]; then
  warn "WORKSHOP_ROOM_PASSWORD is not set — cannot fetch the model-proxy key."
  warn "Set it in the 'Create codespace with options…' dialog (the room password from the workshop host),"
  warn "then rebuild. Without it the agents + Phoenix/dt-evals evals have no model key (the rest still installs)."
  exit 1
fi

if ! have node; then
  err "node not found — needed to parse the dispenser response. It is baked into the image; re-run inside the Codespace."
  exit 1
fi

log "dispense: requesting a virtual key from ${DISPENSER_URL} (room-password auth)"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
# curl's -w prints the status code (000 on a connection failure) regardless of its
# own exit status, so capture that; `|| true` keeps the non-zero exit from aborting.
code="$(curl -sS -o "$tmp" -w '%{http_code}' \
  -H "X-Room-Password: ${WORKSHOP_ROOM_PASSWORD}" \
  --max-time 30 "${DISPENSER_URL}" 2>/dev/null || true)"
code="${code:-000}"

case "$code" in
  200) : ;;
  401) err "dispenser returned 401 — wrong or missing room password. Fix WORKSHOP_ROOM_PASSWORD and re-run."; exit 1 ;;
  000) err "could not reach the dispenser at ${DISPENSER_URL} (network/DNS/timeout). Is the proxy host up?"; exit 1 ;;
  *)   err "dispenser returned HTTP ${code}. Body: $(head -c 200 "$tmp")"; exit 1 ;;
esac

# Parse {proxy_url, virtual_key, model} without assuming jq is installed.
if ! read -r PROXY_URL VKEY MODEL < <(node -e '
  let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{
    try{
      const o=JSON.parse(s);
      const pu=(o.proxy_url||"").replace(/\/+$/,"");
      process.stdout.write([pu, o.virtual_key||"", o.model||"deepseek-chat"].join(" ")+"\n");
    }catch(e){ process.exit(3); }
  });' < "$tmp"); then
  err "could not parse the dispenser response as JSON (HTTP 200 but unexpected body)."
  exit 1
fi

if [ -z "${PROXY_URL}" ] || [ -z "${VKEY}" ]; then
  err "dispenser response is missing proxy_url or virtual_key."
  exit 1
fi

# Two base-URL forms from the single proxy_url:
#   /v1 form    — OpenAI SDK / kagent / Phoenix (DEEPSEEK_BASE_URL, OPENAI_BASE_URL)
#   bare form   — the dt-evals validate probe hardcodes ${baseUrl}/v1/chat/completions,
#                 so its judge baseUrl must NOT carry /v1 (would double it → 404).
BASE_V1="${PROXY_URL%/v1}/v1"
BASE_NOV1="${PROXY_URL%/v1}"

umask 077
cat > "$OUT" <<EOF
# Auto-generated by .devcontainer/bootstrap/dispense-llm.sh (ISI-6996). GITIGNORED.
# Per-attendee LiteLLM-proxy endpoint + a minted, budget-capped virtual key, fetched
# from the room dispenser using WORKSHOP_ROOM_PASSWORD. Regenerate by re-running that
# script (e.g. after the room password rotates). NEVER commit this file.
export WORKSHOP_LLM_MODEL="${MODEL}"
export WORKSHOP_LLM_BASE_URL="${BASE_V1}"
export WORKSHOP_LLM_BASE_URL_NOV1="${BASE_NOV1}"
export WORKSHOP_LLM_API_KEY="${VKEY}"
# Back-compat names the existing consumers already read (kagent secret source via
# cluster/secrets.sh, the Phoenix container + Python evals, and the dt-evals judge
# key fallback). All now carry the proxy endpoint + virtual key — no raw key anywhere.
export DEEPSEEK_API_KEY="${VKEY}"
export DEEPSEEK_BASE_URL="${BASE_V1}"
export OPENAI_API_KEY="${VKEY}"
export OPENAI_BASE_URL="${BASE_V1}"
EOF
chmod 600 "$OUT"
ok "wrote ${OUT#"${REPO_ROOT}"/} (model=${MODEL}, base=${BASE_V1}, key=sk-***masked***)"

# Surface the wiring to every interactive shell: the Phoenix Python evals read
# OPENAI_API_KEY / OPENAI_BASE_URL straight from the attendee's shell. Idempotent
# guard block — appended once, keyed on the marker.
BRC="${HOME}/.bashrc"
MARK="# >>> workshop-llm (ISI-6996) >>>"
if [ -w "${HOME}" ] && { [ ! -f "$BRC" ] || ! grep -qF "$MARK" "$BRC"; }; then
  {
    echo ""
    echo "$MARK"
    echo "[ -f \"${OUT}\" ] && . \"${OUT}\""
    echo "# <<< workshop-llm (ISI-6996) <<<"
  } >> "$BRC"
  ok "sourced ${OUT#"${REPO_ROOT}"/} from ~/.bashrc — new terminals reach DeepSeek via the proxy"
fi
